// Service worker ที่ **ไม่แคชอะไรเลยโดยตั้งใจ**
//
// มีไว้ทำอย่างเดียว: ทำให้เบราว์เซอร์ยอมให้ติดตั้งเป็นแอปบนหน้าจอโฮม (PWA
// ต้องมี SW ที่ควบคุมหน้าอยู่) แอปนี้ทั้งแอปคือ "ตอนนี้อยู่ที่ไหน สถานะวันนี้
// เป็นยังไง" การเสิร์ฟหน้าเก่าจากแคชคือการโกหกเรื่องที่สำคัญที่สุดของมัน —
// พนักงานจะเห็นว่า "ยังไม่ได้ลงเวลา" ทั้งที่ลงไปแล้ว หรือกลับกัน
//
// ถ้าวันหนึ่งจะเพิ่มแคชจริง ให้แคชเฉพาะ static asset (/assets/**) และห้ามแตะ
// ผลลัพธ์ของ callable เด็ดขาด
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => e.waitUntil(self.clients.claim()));
