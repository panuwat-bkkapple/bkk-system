const KEY = 'bkk_employee_onboarded_v1';

/** เคยดูหน้าแนะนำแล้วหรือยัง — อ่าน/เขียนพังได้โดยไม่ทำให้แอปล่ม
 *  (โหมดส่วนตัวของ Safari โยน error ตอนแตะ localStorage) */
export function onboardingSeen(): boolean {
  try { return localStorage.getItem(KEY) === '1'; } catch { return false; }
}
export function markOnboardingSeen(): void {
  try { localStorage.setItem(KEY, '1'); } catch { /* ไม่เป็นไร แค่จะโชว์อีกรอบ */ }
}

/** หน้าแนะนำแทรกก่อนหน้าล็อกอินเท่านั้น
 *
 * **ห้ามแทรกก่อนจอ `geo`** — ลำดับ "ตรวจตัวตนก่อนขออะไรจากเครื่องเขา" เป็น
 * การแก้บั๊กจริง (#726) หน้าแนะนำจึงเป็นแค่ข้อมูล ไม่ขอสิทธิ์อะไรทั้งสิ้น
 * ตัวขอสิทธิ์ตำแหน่งยังเป็นจอ `geo` ซึ่งอยู่หลัง `employeeMe` เหมือนเดิม
 */
export function shouldShowOnboarding(screen: string, seen: boolean): boolean {
  return screen === 'login' && !seen;
}
