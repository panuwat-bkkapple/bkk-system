/** สัดส่วนของรางที่ต้องลากถึงจึงจะนับว่ายืนยัน
 *
 *  ไม่ใช้ 1.0 เพราะนิ้วมักปล่อยก่อนสุดรางจริงๆ และ 0.85 ยังไกลพอที่จะไม่เกิด
 *  จากการปัดพลาด — แยกไฟล์เพื่อให้เทสได้โดยไม่ต้องมีเบราว์เซอร์
 */
export const CONFIRM_RATIO = 0.85;

/** ตรรกะเดียวที่ตัดสินว่า "ลากถึงหรือยัง" */
export function reachedConfirm(dx: number, max: number): boolean {
  return max > 0 && dx >= max * CONFIRM_RATIO;
}
