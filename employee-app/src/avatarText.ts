/** อักษรย่อจากชื่อ สำหรับวงกลมโปรไฟล์ตอนที่ยังไม่มีรูป
 *
 * `employees/{id}/photo_url` ส่วนใหญ่เป็น null จริงๆ (ฝ่ายบุคคลยังไม่ได้อัปโหลด)
 * วงกลมเปล่าจึงเป็นสิ่งที่คนเห็นบ่อยกว่ารูป — ใช้อักษรย่อแทนไอคอนคนซ้ำกันทุกคน
 * เพราะอักษรย่อยังบอกได้ว่าล็อกอินอยู่ในบัญชีใคร
 *
 * แยกไฟล์จาก `Avatar.tsx` เพราะ eslint (react-refresh) ห้ามไฟล์คอมโพเนนต์
 * export ค่าที่ไม่ใช่คอมโพเนนต์ — และแยกแล้วเทสได้โดยไม่ต้อง render
 */
export function initialsOf(name: string): string {
  const parts = String(name || '').trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return '?';
  // ชื่อไทยเขียนติดกันเป็นคำเดียวได้ — คำเดียวเอาสองอักษรแรก, สองคำขึ้นไป
  // เอาอักษรแรกของสองคำแรก. ใช้ spread เพื่อนับเป็น "ตัวอักษร" ไม่ใช่ code unit
  if (parts.length === 1) return [...parts[0]].slice(0, 2).join('');
  return [...parts[0]][0] + [...parts[1]][0];
}
