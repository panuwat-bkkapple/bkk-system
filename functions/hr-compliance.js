const { bkkDayIndex } = require("./hr-documents");

// ม.34 พ.ร.บ.ประกันสังคม — นายจ้างต้องยื่นแบบขึ้นทะเบียนผู้ประกันตน (สปส.1-03)
// ภายใน 30 วันนับแต่วันที่ลูกจ้างเข้าทำงาน
const SSO_REGISTER_DAYS = 30;

// เตือนล่วงหน้าก่อนถึงกำหนด — 7 วันพอให้ยื่นทัน แต่ไม่นานจนกลายเป็นป้ายที่ติด
// อยู่ตลอดเวลาแล้วไม่มีใครมอง
const SSO_WARN_LEAD_DAYS = 7;

const str = (v) => String(v == null ? "" : v).trim();

// ลูกจ้างที่อยู่ในระบบประกันสังคม ม.33 = คนที่เข้ารอบจ่ายเงินเดือน
// ฟรีแลนซ์เดินคนละเส้น (หัก ณ ที่จ่าย 3% ตอนถอน — rider-wht.js)
const inSsoScheme = (e) =>
  ["monthly", "daily"].includes(str((e || {}).employment_type).toLowerCase());

const EX_STATUSES = ["resigned", "terminated"];

/**
 * สถานะการขึ้นทะเบียนประกันสังคมของคนหนึ่งคน
 *
 * `state`:
 *   `ok`            มีเลขผู้ประกันตนแล้ว
 *   `not_required`  ฟรีแลนซ์ หรือพ้นสภาพไปแล้ว (ไม่มีอะไรให้ทำต่อ)
 *   `unknown`       ไม่มีวันเริ่มงาน — คำนวณกำหนดไม่ได้ **ห้ามอ่านว่าไม่มีปัญหา**
 *   `pending`       ยังอยู่ในกำหนด
 *   `due_soon`      เหลือไม่เกิน 7 วัน
 *   `overdue`       เลยกำหนด 30 วันแล้ว
 *
 * **`unknown` ไม่ใช่ `ok`** — คนที่ไม่มีวันเริ่มงานในระบบอาจเข้าทำงานมาแล้วครึ่งปี
 * การเงียบให้เขาคือการเดาไปทางที่สบายกว่า
 */
function ssoRegistrationState({ employee, priv, now = Date.now() } = {}) {
  const emp = employee || {};
  const p = priv || {};

  if (!inSsoScheme(emp)) return { state: "not_required", reason: "ไม่ได้อยู่ในระบบเงินเดือน" };
  if (str(p.social_security_no)) return { state: "ok" };
  if (EX_STATUSES.includes(str(emp.status).toLowerCase())) {
    return { state: "not_required", reason: "พ้นสภาพแล้ว" };
  }

  const hiredAt = Number(emp.hired_at);
  if (!Number.isFinite(hiredAt) || hiredAt <= 0) {
    return { state: "unknown", reason: "ไม่มีวันเริ่มงานในระบบ จึงคำนวณกำหนดยื่นไม่ได้" };
  }

  // นับวันแบบเดียวกับที่เอกสารบุคคลนับ (วันเริ่มงาน = วันที่ 1)
  const daysSince = bkkDayIndex(now) - bkkDayIndex(hiredAt) + 1;
  const daysLeft = SSO_REGISTER_DAYS - daysSince;

  if (daysLeft < 0) return { state: "overdue", daysSince, daysLeft };
  if (daysLeft <= SSO_WARN_LEAD_DAYS) return { state: "due_soon", daysSince, daysLeft };
  return { state: "pending", daysSince, daysLeft };
}

/** ข้อความสำหรับคนอ่าน — เก็บไว้ที่เดียวเพื่อให้ทุกจอพูดเหมือนกัน */
function ssoStateMessage(s) {
  const st = (s || {}).state;
  if (st === "overdue") {
    return `เลยกำหนดขึ้นทะเบียนประกันสังคมมา ${Math.abs(s.daysLeft)} วัน (ต้องยื่นภายใน ${SSO_REGISTER_DAYS} วันนับแต่วันเริ่มงาน)`;
  }
  if (st === "due_soon") {
    return `ต้องขึ้นทะเบียนประกันสังคมภายในอีก ${s.daysLeft} วัน`;
  }
  if (st === "unknown") return "ยังไม่มีเลขผู้ประกันตน และไม่มีวันเริ่มงานให้คำนวณกำหนดยื่น";
  return null;
}

/**
 * ช่องทางจ่ายที่ประกาศไว้ — `transfer` เป็นค่าตั้งต้นเพราะบริษัทโอนเงินเดือน
 *
 * ค่าที่อ่านไม่ออกตกเป็น `transfer` ด้วย: เดาว่าเป็นเงินสดแปลว่ายอดหลุดออกจาก
 * ถังที่ต้องเตรียมสลิปโอนโดยไม่มีใครสังเกต ส่วนเดาว่าเป็นโอนอย่างมากก็ทำให้
 * ต้องมากรอกเลขบัญชี ซึ่งดังพอให้แก้
 */
const payMethodOf = (priv) =>
  str(((priv || {}).pay || {}).pay_method).toLowerCase() === "cash" ? "cash" : "transfer";

/**
 * ความพร้อมของบรรทัดหนึ่งบรรทัดในรอบจ่าย
 *
 * คืนสองช่องแยกกันโดยตั้งใจ:
 *   `blocking` — ทำให้ยอดนี้จ่ายไม่ได้จริง → กันการอนุมัติทั้งรอบ
 *   `warnings` — เรื่องที่ต้องรู้ แต่ไม่ได้ทำให้สลิปใบนี้ผิด → ไม่กัน
 *
 * เอาสองอย่างมาปนกันเมื่อไหร่ ทางเลือกจะเหลือแค่ "บล็อกเกินจนคนหาทางข้าม"
 * กับ "เตือนแล้วไม่มีใครอ่าน"
 */
function payrollReadiness({ employee, priv, now = Date.now() } = {}) {
  const p = priv || {};
  const warnings = [];
  let blocking = null;

  const method = payMethodOf(p);
  const account = str((p.bank || {}).account).replace(/[\s-]/g, "");
  if (method === "transfer" && !account) {
    blocking = "ยังไม่มีเลขบัญชีธนาคาร — กรอกเลขบัญชี หรือถ้าคนนี้รับเงินสด ให้ตั้งช่องทางจ่ายเป็นเงินสด";
  }

  const sso = ssoRegistrationState({ employee, priv: p, now });
  const msg = ssoStateMessage(sso);
  if (msg && (sso.state === "overdue" || sso.state === "unknown")) warnings.push(msg);

  return { blocking, warnings, pay_method: method, sso_state: sso.state };
}

module.exports = {
  SSO_REGISTER_DAYS, SSO_WARN_LEAD_DAYS,
  inSsoScheme, ssoRegistrationState, ssoStateMessage,
  payMethodOf, payrollReadiness,
};
