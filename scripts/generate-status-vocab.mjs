#!/usr/bin/env node
// Generates functions/status-vocab.generated.js from src/types/job-statuses.ts.
//
// Why this exists: functions/ is plain JS with its own rootDir and cannot import
// the canonical TS enum, so the status vocabulary used to be hand-copied into
// functions/email.js and functions/index.js. The CI sync check only ever
// compared the three TS copies across repos, so those two JS copies could (and
// did) drift: on 1 Sep 2026 both were missing the 'Sent to QC Lab' and
// 'Ready to Sell' aliases that the TS source had gained, and functions/index.js
// was missing 'Waiting for Handover' on top of that — together 114 of the ~499
// live jobs that runStatusMigration was written to rename and silently skipped.
//
// Usage:
//   node scripts/generate-status-vocab.mjs          # write the generated file
//   node scripts/generate-status-vocab.mjs --check  # exit 1 if it is stale
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(root, "src/types/job-statuses.ts");
const OUT = path.join(root, "functions/status-vocab.generated.js");

export async function renderStatusVocab() {
  const source = readFileSync(SRC, "utf8");
  const result = await build({
    entryPoints: [SRC],
    // The enum file imports nothing, so transpile-only keeps the output a
    // readable 1:1 translation rather than an opaque bundle.
    bundle: false,
    format: "cjs",
    platform: "node",
    target: "node22",
    write: false,
  });
  const banner = [
    "// @generated by scripts/generate-status-vocab.mjs — DO NOT EDIT BY HAND.",
    "//",
    "// Transpiled from src/types/job-statuses.ts, which is the source of truth and",
    "// is mirrored byte-for-byte into bkk-frontend-next and bkk-rider-app (see",
    "// .github/workflows/sync-status-enum.yml). Edit the TS file, then run:",
    "//   npm run generate:status-vocab",
    "//",
    `// source-sha256: ${createHash("sha256").update(source).digest("hex")}`,
    "",
  ].join("\n");
  // LEGACY_ALIAS is module-private in the TS source (nothing in the app needs
  // it by name — normalizeStatus is the API). functions/ does: query lists for
  // fetchJobsByStatuses must name EVERY spelling stored in the DB, and the
  // only honest source of "which legacy spellings map here" is this table.
  // Appended here rather than exported from the TS file because that file is
  // mirrored byte-for-byte into two other repos (Data Contracts #6).
  const aliasExport = [
    "",
    "// Appended by scripts/generate-status-vocab.mjs: the alias table for",
    "// functions/status-match.js (query lists must name every stored spelling).",
    "module.exports.LEGACY_ALIAS = LEGACY_ALIAS;",
    "",
  ].join("\n");
  return banner + result.outputFiles[0].text + aliasExport;
}

const rendered = await renderStatusVocab();

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    console.error("status-vocab.generated.js is missing. Run: npm run generate:status-vocab");
    process.exit(1);
  }
  if (current !== rendered) {
    console.error(
      "functions/status-vocab.generated.js is stale — src/types/job-statuses.ts changed.\n" +
        "Run: npm run generate:status-vocab  (and commit the result)"
    );
    process.exit(1);
  }
  console.log("functions/status-vocab.generated.js is up to date.");
} else {
  writeFileSync(OUT, rendered);
  console.log(`Wrote ${path.relative(root, OUT)}`);
}
